"""
The single source of typsphinx's Typst Universe ``@preview`` dependencies.

Every build writes ``<outdir>/_typsphinx/deps.typ`` (see
``TypstBuilder._write_dependencies_file()``): the five ``#import`` lines
below plus a ``typsphinx-init`` show function that sets up codly. Every
content file, every wrapper, and the bundled ``templates/base.typ`` import
that one file by the root-absolute path ``/_typsphinx/deps.typ`` instead of
pinning versions themselves, so a version bump happens here and nowhere
else.

The package specs are full literal strings on purpose -- never a name and
version joined at runtime -- so a plain grep for ``@preview/<name>:`` finds
the one place they are defined.

This module is a leaf: it imports nothing from the rest of typsphinx.
"""

from dataclasses import dataclass

#: Outdir-relative directory the generated dependencies file is written to.
DEPS_OUTPUT_DIR = "_typsphinx"

#: Basename of the generated dependencies file.
DEPS_FILENAME = "deps.typ"

#: Root-absolute Typst import path of the dependencies file (compile root =
#: outdir).
DEPS_IMPORT_PATH = "/_typsphinx/deps.typ"

#: Name of the show function ``deps.typ`` exports to initialise packages.
INIT_FUNCTION_NAME = "typsphinx-init"


@dataclass(frozen=True)
class PreviewPackage:
    """One Typst Universe package import of the default ``deps.typ``.

    Attributes:
        spec: The full package spec, e.g. ``"@preview/codly:1.3.0"``.
        items: The import list after the colon, e.g. ``"*"``,
            ``"mi, mitex"`` or ``"render"``.
    """

    spec: str
    items: str

    @property
    def name(self) -> str:
        """The package name, e.g. ``"codly"``."""
        return self.spec.split("/", 1)[1].split(":", 1)[0]

    @property
    def version(self) -> str:
        """The package version, e.g. ``"1.3.0"``."""
        return self.spec.rsplit(":", 1)[1]

    def import_line(self) -> str:
        """The Typst ``#import`` line for this package."""
        return f'#import "{self.spec}": {self.items}'


#: The default packages, in ``deps.typ`` import order.
DEFAULT_PACKAGES: tuple[PreviewPackage, ...] = (
    PreviewPackage(spec="@preview/codly:1.3.0", items="*"),
    PreviewPackage(spec="@preview/codly-languages:0.1.10", items="*"),
    PreviewPackage(spec="@preview/mitex:0.2.7", items="mi, mitex"),
    PreviewPackage(spec="@preview/gentle-clues:1.3.1", items="*"),
    PreviewPackage(spec="@preview/diagraph:0.3.7", items="render"),
)

# The codly initialisation every content file and wrapper applies through
# `#show: typsphinx-init`. A top-level show rule does not cross #include(),
# so each file applies it itself; this text lives only here.
_INIT_FUNCTION = (
    f"#let {INIT_FUNCTION_NAME}(body) = {{\n"
    "  show: codly-init.with()\n"
    "  codly(languages: codly-languages)\n"
    "  body\n"
    "}\n"
)


def render_default_deps() -> str:
    """Return the full text of the default ``deps.typ``.

    Returns:
        The five ``#import`` lines of ``DEFAULT_PACKAGES`` in order, followed
        by the ``typsphinx-init`` show function.
    """
    lines = [
        "// Generated by typsphinx: the Typst Universe packages every content",
        "// file and wrapper imports through /_typsphinx/deps.typ.",
    ]
    lines.extend(package.import_line() for package in DEFAULT_PACKAGES)
    lines.append("")
    lines.append(
        "// Package initialisation, applied by every content file and wrapper."
    )
    return "\n".join(lines) + "\n" + _INIT_FUNCTION


def deps_preamble_lines() -> list[str]:
    """Return the two-line preamble every content file and wrapper starts with.

    Returns:
        ``['#import "/_typsphinx/deps.typ": *', '#show: typsphinx-init']``
    """
    return [f'#import "{DEPS_IMPORT_PATH}": *', f"#show: {INIT_FUNCTION_NAME}"]
