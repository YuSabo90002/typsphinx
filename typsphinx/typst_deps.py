"""
The single source of typsphinx's Typst Universe ``@preview`` dependencies.

Every build writes ``<outdir>/_typsphinx/deps.typ`` (see
``TypstBuilder._write_dependencies_file()``): the five ``#import`` lines
below plus a ``typsphinx-init`` show function that registers the
``codly-languages`` table with codly 2.0 (``codly.lang-set_``). codly is
imported as a module (``as codly``), not with ``*``: codly 2.0's top level
defines ``line``, ``highlight``, ``info`` and other names that would shadow
Typst builtins and typsphinx's own output, and every code block is emitted
as an explicit ``codly.new(raw(...), ...)`` call. No ``show raw`` rule is
installed, so a raw block a user writes is left to Typst's own rendering.
Every
content file, every wrapper, and the bundled ``templates/base.typ`` import
that one file by the root-absolute path ``/_typsphinx/deps.typ`` instead of
pinning versions themselves, so a version bump happens here and nowhere
else.

The package specs are full literal strings on purpose -- never a name and
version joined at runtime -- so a plain grep for ``@preview/<name>:`` finds
the one place they are defined.

This module is a leaf: it imports nothing from the rest of typsphinx.
"""

import re
from dataclasses import dataclass

#: Outdir-relative directory the generated dependencies file is written to.
DEPS_OUTPUT_DIR = "_typsphinx"

#: Basename of the generated dependencies file.
DEPS_FILENAME = "deps.typ"

#: Root-absolute Typst import path of the dependencies file (compile root =
#: outdir).
DEPS_IMPORT_PATH = "/_typsphinx/deps.typ"

#: Name of the show function ``deps.typ`` exports to initialise packages.
INIT_FUNCTION_NAME = "typsphinx-init"


@dataclass(frozen=True)
class PreviewPackage:
    """One Typst Universe package import of the default ``deps.typ``.

    Exactly one of ``items`` and ``alias`` is set.

    Attributes:
        spec: The full package spec, e.g. ``"@preview/codly:2.0.0"``.
        items: The import list after the colon, e.g. ``"*"``,
            ``"mi, mitex"`` or ``"render"``; empty when ``alias`` is set.
        alias: The module name of an ``#import "SPEC" as ALIAS`` import,
            e.g. ``"codly"``; ``None`` for an item import.

    Raises:
        ValueError: If both or neither of ``items`` and ``alias`` are set.
    """

    spec: str
    items: str = ""
    alias: str | None = None

    def __post_init__(self) -> None:
        if bool(self.items) == (self.alias is not None):
            raise ValueError(
                f"PreviewPackage {self.spec!r}: set exactly one of items and alias"
            )

    @property
    def name(self) -> str:
        """The package name, e.g. ``"codly"``."""
        return self.spec.split("/", 1)[1].split(":", 1)[0]

    @property
    def version(self) -> str:
        """The package version, e.g. ``"2.0.0"``."""
        return self.spec.rsplit(":", 1)[1]

    def import_line(self) -> str:
        """The Typst ``#import`` line for this package.

        ``#import "SPEC" as ALIAS`` when ``alias`` is set, otherwise
        ``#import "SPEC": ITEMS``.
        """
        if self.alias is not None:
            return f'#import "{self.spec}" as {self.alias}'
        return f'#import "{self.spec}": {self.items}'


#: The default packages, in ``deps.typ`` import order.
DEFAULT_PACKAGES: tuple[PreviewPackage, ...] = (
    PreviewPackage(spec="@preview/codly:2.0.0", alias="codly"),
    PreviewPackage(spec="@preview/codly-languages:0.1.10", items="*"),
    PreviewPackage(spec="@preview/mitex:0.2.7", items="mi, mitex"),
    PreviewPackage(spec="@preview/gentle-clues:1.3.1", items="*"),
    PreviewPackage(spec="@preview/diagraph:0.3.7", items="render"),
)

# The codly initialisation every content file and wrapper applies through
# `#show: typsphinx-init`. A top-level show rule does not cross #include(),
# so each file applies it itself; this text lives only here. It only
# registers the codly-languages table (badge names, icons, colours) for the
# explicit codly.new(...) calls typsphinx emits; it installs no `show raw`
# rule and sets no other codly field, so codly 2.0's defaults apply.
_INIT_FUNCTION = (
    f"#let {INIT_FUNCTION_NAME}(body) = {{\n"
    "  show: codly.lang-set_(languages: codly-languages)\n"
    "  body\n"
    "}\n"
)


def render_default_deps() -> str:
    """Return the full text of the default ``deps.typ``.

    Returns:
        The five ``#import`` lines of ``DEFAULT_PACKAGES`` in order, followed
        by the ``typsphinx-init`` show function.
    """
    lines = [
        "// Generated by typsphinx: the Typst Universe packages every content",
        "// file and wrapper imports through /_typsphinx/deps.typ.",
    ]
    lines.extend(package.import_line() for package in DEFAULT_PACKAGES)
    lines.append("")
    lines.append(
        "// Package initialisation, applied by every content file and wrapper."
    )
    return "\n".join(lines) + "\n" + _INIT_FUNCTION


def deps_preamble_lines() -> list[str]:
    """Return the two-line preamble every content file and wrapper starts with.

    Returns:
        ``['#import "/_typsphinx/deps.typ": *', '#show: typsphinx-init']``
    """
    return [f'#import "{DEPS_IMPORT_PATH}": *', f"#show: {INIT_FUNCTION_NAME}"]


# The five default package names, longest alternative first so `codly`
# never wins over `codly-languages`. The `:` must follow the name
# immediately, and only the `@preview/` namespace is matched.
_PREVIEW_PIN_RE = re.compile(
    r"@preview/(codly-languages|codly|mitex|gentle-clues|diagraph):" r"(\d+\.\d+\.\d+)"
)


def strip_typst_comments(text: str) -> str:
    """Return ``text`` with Typst ``//`` and ``/* */`` comments removed.

    A single left-to-right character scan, not a regex:

    - a double-quoted string literal is copied through unchanged, honouring
      backslash escapes; it ends at an unescaped ``"`` or at the end of the
      line, so ``"https://example.com"`` is never read as a ``//`` comment;
    - a ``/* ... */`` block comment is removed with nesting-depth counting,
      as Typst nests block comments (an unterminated one runs to the end of
      the text); it is replaced by one space so the text on either side is
      never joined;
    - a ``//`` line comment is removed up to, not including, the newline.

    Known limit (accepted as a best-effort aid): the scanner does not track
    Typst's markup/code modes, so a ``"`` in markup-mode prose is treated as
    a string delimiter too, up to the next ``"`` or the end of that line.

    Args:
        text: Typst source text.

    Returns:
        The text with comments removed and everything else unchanged.
    """
    out: list[str] = []
    i = 0
    n = len(text)
    while i < n:
        ch = text[i]
        if ch == '"':
            # String literal: copy through to the closing quote or newline.
            j = i + 1
            while j < n:
                c = text[j]
                if c == "\\" and j + 1 < n and text[j + 1] != "\n":
                    j += 2
                    continue
                if c == '"':
                    j += 1
                    break
                if c == "\n":
                    break
                j += 1
            out.append(text[i:j])
            i = j
        elif text.startswith("/*", i):
            depth = 1
            j = i + 2
            while j < n and depth:
                if text.startswith("/*", j):
                    depth += 1
                    j += 2
                elif text.startswith("*/", j):
                    depth -= 1
                    j += 2
                else:
                    j += 1
            out.append(" ")
            i = j
        elif text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j == -1 else j
        else:
            out.append(ch)
            i += 1
    return "".join(out)


def extract_preview_versions(text: str) -> dict[str, set[str]]:
    """Return every version of the five default packages pinned in ``text``.

    The text is comment-stripped first (``strip_typst_comments()``), then
    only ``@preview/<name>:<major>.<minor>.<patch>`` for the five default
    package names is matched; any other package, and any other namespace
    such as ``@local/``, is ignored.

    Args:
        text: Typst source text.

    Returns:
        A mapping from package name to the set of versions found; a package
        that is not pinned is absent.
    """
    found: dict[str, set[str]] = {}
    for match in _PREVIEW_PIN_RE.finditer(strip_typst_comments(text)):
        found.setdefault(match.group(1), set()).add(match.group(2))
    return found


def version_sort_key(version: str) -> tuple[int, ...]:
    """Numeric ``(major, minor, patch)`` sort key for a version string."""
    return tuple(int(part) for part in version.split("."))
